#!/usr/bin/env python3
"""
Rebuilds the generated by-category skill junctions from src/.agents/skills
(source of truth).

Generated (gitignored) output:
    src/skills/<category>/<name>   by purpose, categories from categories.json

Only link entries in the output folders are removed/recreated. Real files and
folders are left alone. An entry in src/.agents/skills that is a plain file
(git symlink checked out with core.symlinks=false) is treated as a pointer:
its content is the target directory.

On Windows, directory junctions are used (no admin needed).
On macOS/Linux, symbolic links are used.
"""

import json
import os
import stat
import subprocess
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_categories(config_path: Path) -> dict:
    with open(config_path, "r", encoding="utf-8") as f:
        return json.load(f)


def scan_skills(source_dir: Path) -> dict[str, str]:
    """Scan source skills directory and return {name: target_path}."""
    skills: dict[str, str] = {}
    if not source_dir.exists():
        print(f"ERROR: Source directory not found: {source_dir}")
        sys.exit(1)

    for item in sorted(source_dir.iterdir()):
        if item.name == ".gitkeep":
            continue

        if item.is_dir():
            skills[item.name] = str(item.resolve())
        else:
            # Pointer file: content is the target directory
            content = item.read_text(encoding="utf-8").strip()
            pointer_target = Path(content)
            if not pointer_target.is_absolute():
                pointer_target = (item.parent / pointer_target).resolve()
            if not pointer_target.is_dir():
                print(
                    f"WARNING: Skipping {item.name}: pointer target missing ({pointer_target})"
                )
                continue
            skills[item.name] = str(pointer_target)

    return skills


def get_category(name: str, config: dict) -> str:
    """Determine category for a skill name."""
    # Explicit categories
    categories = config.get("categories", {})
    for cat_name, cat_skills in categories.items():
        if name in cat_skills:
            return cat_name

    # Prefix matching
    prefixes = config.get("prefixes", {})
    matches = [(prefix, cat) for prefix, cat in prefixes.items() if name.startswith(prefix)]
    if matches:
        # Longest prefix wins
        matches.sort(key=lambda x: len(x[0]), reverse=True)
        return matches[0][1]

    return config.get("default", "general")


def is_link(path: Path) -> bool:
    """Check if path is a symlink or junction."""
    if path.is_symlink():
        return True
    if os.name == "nt" and path.exists():
        try:
            st = os.lstat(path)
            if hasattr(st, "st_file_attributes"):
                return (
                    bool(st.st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)
                    and path.is_dir()
                )
        except (OSError, AttributeError):
            pass
    return False


def remove_link(path: Path) -> None:
    """Remove a link without affecting the target."""
    if path.is_symlink():
        os.unlink(path)
    elif os.name == "nt" and path.is_dir():
        # Junction
        os.rmdir(path)
    else:
        (os.unlink if path.is_file() else os.rmdir)(path)


def create_link(link: Path, target: Path) -> None:
    """Create a junction (Windows) or symlink (macOS/Linux)."""
    link.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        # Use junction on Windows for directories (no admin needed)
        if link.exists() or link.is_symlink():
            remove_link(link)
        result = subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(link), str(target)],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            raise RuntimeError(f"Failed to create junction: {result.stderr.strip()}")
    else:
        os.symlink(target, link, target_is_directory=True)


def clear_links(dir_path: Path) -> None:
    """Remove all links in a directory, warn on real files/folders."""
    if not dir_path.exists():
        return

    for item in dir_path.iterdir():
        if item.name == ".gitkeep":
            continue
        if is_link(item):
            remove_link(item)
        else:
            print(f"WARNING: Not a link, left alone: {item}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    script_dir = Path(__file__).parent
    repo_root = script_dir.parent.parent.resolve()

    source_dir = repo_root / "src" / ".agents" / "skills"
    categories_path = script_dir / "categories.json"
    skills_dir = repo_root / "src" / "skills"

    config = load_categories(categories_path)
    skills = scan_skills(source_dir)

    # Ensure skills dir exists
    skills_dir.mkdir(parents=True, exist_ok=True)

    # Clear old links in category directories
    for cat_dir in skills_dir.iterdir():
        if not cat_dir.is_dir():
            continue
        if is_link(cat_dir):
            print(f"WARNING: Unexpected link, left alone: {cat_dir}")
            continue
        clear_links(cat_dir)
        # Remove empty category directory
        try:
            remaining = [r for r in cat_dir.iterdir() if r.name != ".gitkeep"]
            if not remaining:
                for r in cat_dir.iterdir():
                    r.unlink()
                cat_dir.rmdir()
        except OSError:
            pass

    # Create new links
    counts: dict[str, int] = {}
    for name, target in sorted(skills.items()):
        category = get_category(name, config)
        cat_dir = skills_dir / category
        cat_dir.mkdir(parents=True, exist_ok=True)

        link_path = cat_dir / name
        try:
            create_link(link_path, Path(target))
            counts[category] = counts.get(category, 0) + 1
        except Exception as e:
            print(f"ERROR: Failed to create link for {name}: {e}")

    print(f"Skills: {len(skills)}")
    for cat, count in sorted(counts.items()):
        print(f"  skills/{cat}: {count}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
