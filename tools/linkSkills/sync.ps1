<#
.SYNOPSIS
  Rebuilds the generated by-category skill junctions from src/.agents/skills (source of truth).

.DESCRIPTION
  Generated (gitignored) output:
    src/skills/<category>/<name>   by purpose, categories from categories.json

  Only link entries in the output folders are removed/recreated. Real files and
  folders are left alone. An entry in src/.agents/skills that is a plain file
  (git symlink checked out with core.symlinks=false) is treated as a pointer:
  its content is the target directory.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repo      = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$src       = Join-Path $repo 'src'
$sourceDir = Join-Path $src '.agents\skills'
$config    = Get-Content (Join-Path $PSScriptRoot 'categories.json') -Raw | ConvertFrom-Json

function Test-Link([System.IO.FileSystemInfo] $item) {
  return [bool]$item.LinkType
}

function Remove-Link([string] $path) {
  [System.IO.Directory]::Delete($path, $false)
}

function Clear-Links([string] $dir) {
  if (-not (Test-Path $dir)) { return }
  foreach ($item in Get-ChildItem $dir -Force) {
    if (Test-Link $item) { Remove-Link $item.FullName }
    elseif ($item.Name -ne '.gitkeep') { Write-Warning "Not a link, left alone: $($item.FullName)" }
  }
}

function Get-Category([string] $name) {
  foreach ($cat in $config.categories.PSObject.Properties) {
    if ($cat.Value -contains $name) { return $cat.Name }
  }
  $match = $config.prefixes.PSObject.Properties |
    Where-Object { $name.StartsWith($_.Name) } |
    Sort-Object { $_.Name.Length } -Descending |
    Select-Object -First 1
  if ($match) { return $match.Value }
  return $config.default
}

$skills = [ordered]@{}
foreach ($item in Get-ChildItem $sourceDir -Force | Sort-Object Name) {
  if ($item.Name -eq '.gitkeep') { continue }
  $target = $item.FullName
  if (-not $item.PSIsContainer) {
    $target = (Get-Content $item.FullName -Raw).Trim()
    if (-not (Test-Path -LiteralPath $target -PathType Container)) {
      Write-Warning "Skipping $($item.Name): pointer target missing ($target)"
      continue
    }
    $target = (Resolve-Path -LiteralPath $target).Path
  }
  $skills[$item.Name] = $target
}

$byPurpose = Join-Path $src 'skills'
New-Item -ItemType Directory -Force -Path $byPurpose | Out-Null
foreach ($dir in Get-ChildItem $byPurpose -Directory -Force) {
  if (Test-Link $dir) { Write-Warning "Unexpected link, left alone: $($dir.FullName)"; continue }
  Clear-Links $dir.FullName
  if (-not (Get-ChildItem $dir.FullName -Force)) { Remove-Item $dir.FullName }
}
$counts = @{}
foreach ($name in $skills.Keys) {
  $cat = Get-Category $name
  $catDir = Join-Path $byPurpose $cat
  New-Item -ItemType Directory -Force -Path $catDir | Out-Null
  New-Item -ItemType Junction -Path (Join-Path $catDir $name) -Target $skills[$name] | Out-Null
  $counts[$cat] = 1 + [int]$counts[$cat]
}

Write-Host "Skills: $($skills.Count)"
$counts.GetEnumerator() | Sort-Object Name | ForEach-Object { Write-Host ("  skills/{0}: {1}" -f $_.Name, $_.Value) }
